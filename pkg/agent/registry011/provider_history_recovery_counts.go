package registry011

import "context"

// These are reconstructed historical successful target reads. They are not
// recovery I/O, a unique object count, or the historical logical-work vector.
type providerHistoryRecoveryReadCount struct {
	objects, bytes uint64
}

func (m *providerHistoryRecoveryInitialModel) addScanReads(out *providerHistoryRecoveryReadCount, copies, bytes uint64) bool {
	r := m.recovery
	payload, a := providerUpperProduct(copies, bytes)
	objects, b := providerUpperSum(out.objects, copies)
	raw, c := providerUpperSum(out.bytes, payload)
	if !a || !b || !c || objects > r.config.bounds.scan.chunkObjects || raw > r.config.bounds.scan.chunkRawBytes ||
		!r.meter.event(providerCompareEvent, 1) {
		return false
	}
	out.objects, out.bytes = objects, raw
	return true
}

// The original pre-I path has setup0 followed by E0. Derive its exact read
// multiplicities from separately verified actual originals. A current HEAD is
// never used as a historical HEAD: both historical pin reads were required to
// equal immutable highwater1, already verified by this pass's legacy replay.
func (m *providerHistoryRecoveryInitialModel) deriveScanReadCounts() ([2]providerHistoryRecoveryReadCount, bool) {
	var out [2]providerHistoryRecoveryReadCount
	if m == nil || m.owner != m || m.complete || m.through != 4 || m.frontier == nil {
		return out, false
	}
	r, p := m.recovery, m.prefix
	if r == nil || p == nil || !p.selectedLocked(r) || p.scan == nil || p.records[0].root == nil ||
		len(p.scan.records) != 2 || p.scan.result.records != 2 || p.records[0].before.ordinal != 0 ||
		p.records[0].after.ordinal != 1 || p.records[0].after.sequence != 1 || len(p.highwaterOriginalBytes) < 2 ||
		len(p.setupOriginalBytes) == 0 || p.anchorBytes == 0 || p.anchorBytes%2 != 0 || r.config.bounds.guardian != nil {
		return out, false
	}
	frame := p.source.frames[0]
	if frame == nil || frame.inventory == nil || len(frame.objects) == 0 || frame.inventory.raw == "" ||
		p.highwaterOriginalBytes[0] == 0 || p.highwaterOriginalBytes[1] == 0 || p.setupOriginalBytes[0] == 0 {
		return out, false
	}
	add := func(index int, copies, bytes uint64) bool { return m.addScanReads(&out[index], copies, bytes) }
	// Constructor: two ANCHORs; controls(): HEAD/highwater1; then setup0.
	if !add(0, 2, p.anchorBytes/2) || !add(0, 2, p.highwaterOriginalBytes[1]) || !add(0, 3, 0) {
		return out, false
	}
	setupBytes, ok := providerUpperSum(out[0].bytes, p.setupOriginalBytes[0])
	if !ok || setupBytes > r.config.bounds.scan.chunkRawBytes || !r.meter.event(providerCompareEvent, 1) {
		return out, false
	}
	out[0].bytes = setupBytes
	// Both the pre-setup anchor loop and the two E0 index checks read the
	// same three typed empty-index originals; repeated reads count again.
	for _, anchor := range m.frontier.anchors {
		raw := p.source.frameObjectObserved(anchor.kind, anchor.digest, 1)
		if len(raw) == 0 || !providerReplayEqual(raw, providerReplayPhaseBytes(anchor.raw, r.meter), r.meter) ||
			!add(0, 1, uint64(len(raw))) || !add(1, 2, uint64(len(raw))) {
			return out, false
		}
	}
	if len(m.frontier.anchors) != 3 {
		return out, false
	}
	// Main intent and evidence pending are two equal reads, not one file.
	e0 := p.records[0]
	for _, raw := range []string{e0.intent, e0.intent, e0.commit, e0.rawFrontier, frame.inventory.raw} {
		if raw == "" || !add(1, 1, uint64(len(raw))) {
			return out, false
		}
	}
	var mutations int
	for _, object := range frame.objects {
		if !add(1, 1, uint64(len(object.raw))) {
			return out, false
		}
		if !r.meter.event(providerCompareEvent, uint64(len(object.kind))) {
			return out, false
		}
		if object.kind == "index-mutation" {
			mutations++
			if !add(1, 1, uint64(len(object.raw))) {
				return out, false
			}
		}
	}
	// E0 has exactly one operation-index mutation. Semantic replay already
	// checked its generated bytes, predecessor and all three resulting roots.
	if mutations != 1 {
		return out, false
	}
	for _, item := range []struct {
		kind, digest string
		copies       uint64
	}{{"enrollment", e0.root.digest, 3}, {"setup", p.setups[0].claim, 1}, {"setup-commit", p.setups[0].commit, 1}} {
		raw := p.source.frameObjectObserved(item.kind, item.digest, 1)
		if len(raw) == 0 || !add(1, item.copies, uint64(len(raw))) {
			return out, false
		}
	}
	// Main replay, lineage and final pre-receipt pin checks: five highwater1
	// length reads (including historical HEAD aliases), plus highwater0.
	// setupBytes rereads one ANCHOR and three setup originals. Empty locks
	// add two successful objects and zero payload bytes. Classified SCAN and
	// command/chunk controls do not contribute to these target counters.
	if !add(1, 5, p.highwaterOriginalBytes[1]) || !add(1, 1, p.highwaterOriginalBytes[0]) ||
		!add(1, 1, p.anchorBytes/2) || !add(1, 3, 0) || !add(1, 2, 0) {
		return out, false
	}
	setupBytes, ok = providerUpperSum(out[1].bytes, p.setupOriginalBytes[0])
	if !ok || setupBytes > r.config.bounds.scan.chunkRawBytes || !r.meter.event(providerCompareEvent, 1) {
		return out, false
	}
	out[1].bytes = setupBytes
	return out, true
}

func (m *providerHistoryRecoveryInitialModel) verifyScanReadCounts(ctx context.Context) bool {
	counts, ok := m.deriveScanReadCounts()
	if !ok {
		return false
	}
	r, scan := m.recovery, m.prefix.scan
	objects, a := providerUpperSum(counts[0].objects, counts[1].objects)
	bytes, b := providerUpperSum(counts[0].bytes, counts[1].bytes)
	if !a || !b || objects != scan.result.objects || bytes != scan.result.bytes ||
		objects > r.config.bounds.scan.maximumObjects || bytes > r.config.bounds.scan.maximumRawBytes {
		return false
	}
	for index, count := range counts {
		record := scan.records[1-index]
		if !r.meter.event(providerCompareEvent, 1) || record.index != uint64(index) || record.objects != count.objects || record.bytes != count.bytes {
			return false
		}
	}
	// An expected empty lock is the one intentional zero-byte role. The
	// generic reader classifies empty inputs as partial; require that exact
	// stable observed EOF, not missing input or an arbitrary empty DATA file.
	for _, kind := range [2]providerHistoryRecoveryFileKind{providerHistoryRecoveryLockCustody, providerHistoryRecoveryLockEvidence} {
		out, err := r.readSelectedInputLocked(ctx, providerHistoryRecoveryInputSelection{checkpoint: r.initial, kind: kind})
		if err != nil || out == nil || out.state != providerHistoryRecoveryPartialInput || len(out.raw) != 0 {
			return false
		}
	}
	if !r.inputReadyLocked(ctx) {
		return false
	}
	m.scanReadCounts, m.scanReadsVerified = counts, true
	return true
}
